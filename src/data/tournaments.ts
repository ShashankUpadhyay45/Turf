export function getTournamentsByVenueId(venueId: string): Tournament[] {
  return tournaments.filter(
    (t) =>
      t.venueId === venueId &&
      (t.status === 'registration_open' || t.status === 'published' || t.status === 'ongoing'),
  );
}

export function getUpcomingTournaments(): Tournament[] {
  return tournaments.filter(
    (t) => t.status === 'registration_open' || t.status === 'published',
  );
}
