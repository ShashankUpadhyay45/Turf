// Unified catalog of all venues arranged normally by location/city & proximity:
// Gaming zones are seamlessly integrated alongside sports turfs in each city.
export const turfs: Turf[] = [];
for (const city of indianCities) {
  const cityVenues = allRawVenues
    .filter((v) => v.city.toLowerCase() === city.toLowerCase())
    .sort((a, b) => (a.distance ?? 0) - (b.distance ?? 0));
  turfs.push(...cityVenues);
}

// Append any non-city or pending review venues
allRawVenues.forEach((v) => {
  if (!turfs.some((t) => t.id === v.id)) {
    turfs.push(v);
  }
});

